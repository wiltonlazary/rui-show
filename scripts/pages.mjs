// Collects the pages: every src/pages/<id>.jsx exports a page record as its
// default, and this writes src/pages/index.generated.js importing each, in
// file order. A new page is a new file; no shared list is edited by hand.
// The build, `npm run check` and `npm test` run it first.
//
//   node scripts/pages.mjs

import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const PAGES = join(root, 'src', 'pages');
export const GENERATED = join(PAGES, 'index.generated.js');

/** A page file's id: its name, lowercase words joined by dashes. */
export const ID = /^[a-z][a-z0-9]*(-[a-z0-9]+)*$/;

/** The page ids, from the folder's `<id>.jsx` files, sorted. */
export function ids() {
  const names = readdirSync(PAGES)
    .filter(f => f.endsWith('.jsx'))
    .map(f => f.slice(0, -4))
    .sort();
  for (const id of names) if (!ID.test(id)) throw new Error(`rui-show: src/pages/${id}.jsx: a page file is named <id>.jsx, the id in lowercase words joined by dashes`);
  return names;
}

/** The registry's source for these ids. @param {string[]} list */
export function source(list) {
  const name = (/** @type {number} */ i) => `p${i}`;
  return [
    '// Generated by scripts/pages.mjs from the files in src/pages: do not edit.',
    '// Add a page by adding src/pages/<id>.jsx.',
    '',
    ...list.map((id, i) => `import ${name(i)} from './${id}.jsx';`),
    '',
    '/** @type {import(\'../site.js\').PageRecord[]} */',
    `export const pages = [${list.map((_, i) => name(i)).join(', ')}];`,
    '',
  ].join('\n');
}

/** Writes the registry when it changed; returns the ids. */
export function generate() {
  const list = ids();
  const text = source(list);
  if (!existsSync(GENERATED) || readFileSync(GENERATED, 'utf8') !== text) writeFileSync(GENERATED, text);
  return list;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const list = generate();
  console.log(`pages: ${list.length} (src/pages/index.generated.js)`);
}
